#!/usr/bin/env python3
"""Compile a wide-table data dictionary into a LinkML source schema and a LinkML-Map spec.

The dictionary is the registry's own (field, form, type, label, choices) plus one
curated column, rddc_target, that says where each field lands in RegistryRecord:

  record.<slot>               scalar on the record (id, respondent, sex, birth_year, country)
  disease.<slot>              the single DiseaseAssertion
  answer                      checklist item -> Answer in the SurveyResponse for its form
  answer_onset:<field>        onset of the named checklist item
  answer_text                 free-text item -> Answer.free_text
  med[<n>].<slot>             n-th MedicationReport
  family.<slot>               FamilyHistory
  score:<name>                Score in the SurveyResponse for its form
  document:<type>             DocumentRef
  (blank)                     not mapped; listed in the spec header as a known gap

Choices ("1, Yes | 0, No") become value_mappings from code to label; the target enums
resolve labels through their aliases. Re-run whenever the dictionary changes; the
outputs are committed so the diff of the spec is reviewable.
"""
import argparse, csv, re
from collections import OrderedDict
from pathlib import Path
import yaml
from linkml_runtime import SchemaView

INT, DEC, BOOL = "integer", "float", "boolean"
SCALAR_RANGES = {"record.birth_year": INT, "disease.diagnosis_year": INT}


def parse_choices(s):
    out = OrderedDict()
    for part in filter(None, (p.strip() for p in s.split("|"))):
        code, _, label = part.partition(",")
        out[code.strip()] = label.strip()
    return out


TARGET = None  # SchemaView of registry_record.yaml, set in main()


def enum_keys(cls, slot_name):
    """Map lower-cased permissible-value keys and aliases to the key, for an enum-ranged slot."""
    sl = TARGET.induced_slot(slot_name, cls)
    if sl.range not in TARGET.all_enums():
        return None
    out = {}
    for key, pv in TARGET.get_enum(sl.range).permissible_values.items():
        out[key.lower()] = key
        for al in pv.aliases or []:
            out[str(al).lower()] = key
    return out


def slot(field, cls=None, slot_name=None, choices=None, missing=("",), boolean=False):
    d = OrderedDict(populated_from=field, missing_values=list(missing))
    if choices:
        keys = enum_keys(cls, slot_name) if cls and slot_name else None
        if boolean:
            d["value_mappings"] = {k: ("true" if v.lower() == "yes" else "false") for k, v in choices.items()}
        elif keys:
            # Choice labels become permissible-value keys so the spec validates without warnings.
            d["value_mappings"] = {k: keys.get(v.lower(), v) for k, v in choices.items()}
        else:
            d["value_mappings"] = dict(choices)
    return d


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dictionary", type=Path)
    ap.add_argument("--registry", required=True)
    ap.add_argument("--schema-out", type=Path, required=True)
    ap.add_argument("--spec-out", type=Path, required=True)
    ap.add_argument("--target-schema", type=Path, default=Path(__file__).resolve().parent.parent / "schema" / "registry_record.yaml")
    a = ap.parse_args()
    global TARGET
    TARGET = SchemaView(str(a.target_schema))
    rows = list(csv.DictReader(open(a.dictionary, newline="")))

    # --- source schema: one class, one attribute per column, everything a string ---
    attrs = OrderedDict()
    for r in rows:
        attrs[r["field"]] = OrderedDict(description=r["label"])
        if r["field"] == rows[0]["field"]:
            attrs[r["field"]]["identifier"] = True
    schema = OrderedDict(
        id=f"https://w3id.org/sage/rddc/registry-to-phenopacket/sources/{a.registry}_wide",
        name=f"{a.registry}_wide",
        title=f"{a.registry}: wide-table export (generated from {a.dictionary.name})",
        description="Generated by bin/gen_wide_spec.py from the registry data dictionary. "
                    "One class, one attribute per column; values are strings as exported. Do not edit by hand.",
        prefixes={"linkml": "https://w3id.org/linkml/", "src": f"https://w3id.org/sage/rddc/registry-to-phenopacket/sources/{a.registry}_wide/"},
        default_prefix="src", default_range="string", imports=["linkml:types"],
        classes={"Row": OrderedDict(tree_root=True, attributes=attrs)},
    )

    # --- transform spec ---
    record, disease, family = OrderedDict(), OrderedDict(), OrderedDict()
    forms, meds, docs, unmapped = OrderedDict(), OrderedDict(), [], []
    onsets = {}
    for r in rows:
        t, f, ch = r["rddc_target"].strip(), r["field"], parse_choices(r["choices"])
        if t.startswith("answer_onset:"):
            onsets[t.split(":", 1)[1]] = slot(f, "Answer", "onset_text", choices=ch)
    for r in rows:
        t, f, ch = r["rddc_target"].strip(), r["field"], parse_choices(r["choices"])
        form = forms.setdefault(r["form"], OrderedDict(version=r["form_version"], answers=[], scores=[]))
        if not t:
            unmapped.append(f)
        elif t.startswith("record."):
            record[t[7:]] = slot(f, "RegistryRecord", t[7:], choices=ch)
        elif t.startswith("disease."):
            disease[t[8:]] = slot(f, "DiseaseAssertion", t[8:], choices=ch)
        elif t == "answer":
            ans = OrderedDict(question_id={"value": f}, label={"value": r["label"]}, value=slot(f, "Answer", "value", choices=ch))
            if f in onsets: ans["onset_text"] = onsets[f]
            form["answers"].append({"Answer": OrderedDict(populated_from="Row", slot_derivations=ans)})
        elif t.startswith("answer_onset:"):
            pass
        elif t == "answer_text":
            form["answers"].append({"Answer": OrderedDict(populated_from="Row", slot_derivations=OrderedDict(
                question_id={"value": f}, label={"value": r["label"]}, free_text=slot(f)))})
        elif t.startswith("med["):
            n, s = re.match(r"med\[(\d+)\]\.(\w+)", t).groups()
            meds.setdefault(n, OrderedDict())[s] = slot(f, "MedicationReport", s, choices=ch, boolean=(s == "ongoing"))
        elif t.startswith("family."):
            family[t[7:]] = slot(f, "FamilyHistory", t[7:], choices=ch)
        elif t.startswith("score:"):
            form["scores"].append({"Score": OrderedDict(populated_from="Row", slot_derivations=OrderedDict(
                name={"value": t[6:]}, value=slot(f)))})
        elif t.startswith("document:"):
            docs.append({"DocumentRef": OrderedDict(populated_from="Row", slot_derivations=OrderedDict(
                document_type={"value": t[9:]}, file_name=slot(f)))})
        else:
            raise SystemExit(f"unknown rddc_target {t!r} for field {f}")

    surveys = []
    for name, fm in forms.items():
        if not fm["answers"] and not fm["scores"]:
            continue
        sd = OrderedDict(instrument={"value": name}, version={"value": fm["version"]})
        if fm["answers"]: sd["answers"] = OrderedDict(class_derivations=fm["answers"])
        if fm["scores"]: sd["scores"] = OrderedDict(class_derivations=fm["scores"])
        surveys.append({"SurveyResponse": OrderedDict(populated_from="Row", slot_derivations=sd)})
    rec = OrderedDict(record)
    rec["registry"] = {"value": a.registry}
    rec["diseases"] = OrderedDict(class_derivations=[{"DiseaseAssertion": OrderedDict(populated_from="Row", slot_derivations=disease)}])
    rec["surveys"] = OrderedDict(class_derivations=surveys)
    if meds:
        rec["medications"] = OrderedDict(class_derivations=[{"MedicationReport": OrderedDict(populated_from="Row", slot_derivations=m)} for _, m in sorted(meds.items(), key=lambda kv: int(kv[0]))])
    if family:
        rec["family_history"] = OrderedDict(class_derivations=[{"FamilyHistory": OrderedDict(populated_from="Row", slot_derivations=family)}])
    if docs:
        rec["documents"] = OrderedDict(class_derivations=docs)
    spec = OrderedDict(
        id=f"https://w3id.org/sage/rddc/registry-to-phenopacket/mappings/{a.registry}_to_record",
        title=f"{a.registry} wide export to RegistryRecord (generated)",
        version="0.1.0",
        description=f"Generated by bin/gen_wide_spec.py from {a.dictionary.name}. Columns not mapped: {', '.join(unmapped) or 'none'}.",
        prefixes={"semapv": "https://w3id.org/semapv/vocab/"},
        mapping_method="semapv:ManualMappingCuration",
        class_derivations={"RegistryRecord": OrderedDict(populated_from="Row", slot_derivations=rec)},
    )
    yaml.add_representer(OrderedDict, lambda d, data: d.represent_dict(data.items()))
    hdr = "# GENERATED by bin/gen_wide_spec.py; edit the data dictionary (rddc_target column) and re-run `make spec`.\n"
    a.schema_out.write_text(hdr + yaml.dump(schema, sort_keys=False, width=100))
    a.spec_out.write_text(hdr + yaml.dump(spec, sort_keys=False, width=100))
    print(f"wrote {a.schema_out} and {a.spec_out}; unmapped columns: {unmapped or 'none'}")


if __name__ == "__main__":
    main()
